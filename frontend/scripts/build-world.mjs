// Builds the world map data from dev-only packages (run again only to refresh it):
//   node scripts/build-world.mjs
// - src/charts/geo/world.json: countries as GeoJSON (Natural Earth 1:110m via world-atlas,
//   public domain), each feature with { key, iso2, iso3, name }. Coordinates rounded.
// - src/charts/geo/countries.ts: every ISO 3166 country: [iso2, iso3, ...English names]
//   (i18n-iso-countries, MIT). Extra aliases live in countryAliases.ts (hand-written).
import fs from "node:fs";
import { createRequire } from "node:module";

const require = createRequire(import.meta.url);
const { feature } = require("topojson-client");
const countries = require("i18n-iso-countries");
const topology = require("world-atlas/countries-110m.json");

const round = (value) => (Array.isArray(value) ? value.map(round) : Math.round(value * 100) / 100);

// Rings that cross the antimeridian (Russia's far east, Fiji) jump from +180 to -180, which
// draws a band across the whole map: shift the western side by 360 and clamp at the edge.
function stitch(ring) {
  const crosses = ring.some((p, i) => i > 0 && Math.abs(p[0] - ring[i - 1][0]) > 180);
  if (!crosses) return ring;
  return ring.map(([lon, lat]) => [Math.min(lon < 0 ? lon + 360 : lon, 180), lat]);
}
function fixGeometry(geometry) {
  if (geometry.type === "Polygon") return { ...geometry, coordinates: geometry.coordinates.map(stitch) };
  if (geometry.type === "MultiPolygon") return { ...geometry, coordinates: geometry.coordinates.map((poly) => poly.map(stitch)) };
  return geometry;
}

const world = feature(topology, topology.objects.countries);
// Antarctica would take a fifth of the map for no data.
world.features = world.features.filter((f) => f.properties.name !== "Antarctica");
let unmatched = [];
const features = world.features.map((f) => {
  const iso2 = f.id ? countries.numericToAlpha2(f.id) : undefined;
  const iso3 = iso2 ? countries.alpha2ToAlpha3(iso2) : undefined;
  const name = f.properties.name;
  if (!iso2) unmatched.push(name);
  return {
    type: "Feature",
    // The key the chart matches data on: the ISO-2 code, else the name (e.g. Kosovo).
    properties: { key: iso2 ?? name, iso2: iso2 ?? null, iso3: iso3 ?? null, name },
    geometry: { type: f.geometry.type, coordinates: round(fixGeometry(f.geometry).coordinates) },
  };
});
fs.mkdirSync(new URL("../src/charts/geo/", import.meta.url), { recursive: true });
fs.writeFileSync(new URL("../src/charts/geo/world.json", import.meta.url), JSON.stringify({ type: "FeatureCollection", features }));

const names = countries.getNames("en", { select: "all" });
const rows = Object.entries(names)
  .map(([iso2, list]) => [iso2, countries.alpha2ToAlpha3(iso2), ...list])
  .sort((a, b) => a[0].localeCompare(b[0]));
const ts = `/** Generated by scripts/build-world.mjs from i18n-iso-countries (MIT). Do not edit:
 * add aliases in countryAliases.ts. Each row: [ISO-2, ISO-3, English names...]. */
export const COUNTRIES: readonly (readonly string[])[] = ${JSON.stringify(rows)};
`;
fs.writeFileSync(new URL("../src/charts/geo/countries.ts", import.meta.url), ts);
console.log(`${features.length} shapes (${unmatched.length} without an ISO code: ${unmatched.join(", ")}), ${rows.length} countries`);
